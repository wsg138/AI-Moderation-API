def rebalance_difficulty():
    """Corpus norm (G02/G08/G09) skews hard; evasion is never trivially easy.
    Rules: minimal-pair records -> hard; evasion-technique records at easy -> medium;
    keep easy only for plain benign controls (greetings/farewells with no trick)."""
    for r in records:
        fam = r['family_id']
        notes = r['notes']
        d = r['difficulty']
        if 'minimal pair' in notes and d in ('easy', 'medium'):
            r['difficulty'] = 'hard'
        elif d == 'easy':
            if 'control' not in notes:
                r['difficulty'] = 'medium'
        elif d == 'medium' and fam.startswith('g15.combo'):
            r['difficulty'] = 'hard'


def main():
    global records, counter
    rebalance_difficulty()
    # quick self-checks before writing
    assert counter[0] == 500, f"expected 500 records, got {counter[0]}"
    ids = [r['example_id'] for r in records]
    assert len(set(ids)) == 500, "duplicate example_ids"
    fams = [r['family_id'] for r in records]
    assert len(set(fams)) == 500, "duplicate family_ids"
    # no slur-adjacent content guard: ensure no record mentions slur families
    for r in records:
        assert 'slur' not in r['family_id'].lower(), r['family_id']
    with open(OUT, 'w') as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')
    print(f"wrote {len(records)} records to {OUT}")

if __name__ == '__main__':
    main()
