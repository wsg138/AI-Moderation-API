    p = PROFILES[profile]
    records.append({
        'example_id': f'G15-{counter[0]:04d}',
        'policy_version': 'v1',
        'source': 'synthetic',
        'domain': domain,
        'difficulty': difficulty,
        'platform_hint': platform,
        'channel_profile': channel,
        'messages': msgs,
        'target_index': target_index,
        'label': label,
        'action': p['action'],
        'review_priority': p['review_priority'],
        'strike': p['strike'],
        'containment': p['containment'],
        'containment_duration_seconds': p['containment_duration_seconds'],
        'support_flow': p['support_flow'],
        'reason_codes': reason_codes,
        'notes': notes,
        'family_id': f'g15.{family}.{counter[0]:03d}',
    })


